#!/usr/bin/env node
/**
 * Generate `db/migrations/pg/*.sql` from `db/migrations/*.sql`.
 *
 * PostgreSQL is the production database. Rather than maintain two hand-written
 * schemas that inevitably drift, the PostgreSQL migration set is *derived* from
 * the SQLite set with a small, auditable set of type rules. `scripts/check-pg-migrations.mjs`
 * fails the build if the generated output is stale, so adding a SQLite
 * migration without regenerating breaks CI on purpose.
 *
 * Usage:  node scripts/gen-pg-migrations.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'db', 'migrations');
const OUT = path.join(SRC, 'pg');

/** Tables whose `status`/`key`-like columns are plain TEXT; everything else is TEXT. */
const BOOLEAN_COLUMNS = new Set([
  'required', 'is_active', 'done', 'client_visible', 'is_done', 'locked', 'billable',
  'acknowledged', 'enforceable', 'persistent', 'deleted', 'read', 'archived', 'pinned',
  'is_partner_visible', 'requires_evidence', 'is_default', 'auto_close', 'resolved',
]);

const INTEGER_HINTS = /(_count|_days|_minutes|_hours_week|_cents|position|points|_ms|size_bytes|_limit|_quota|version_number|order_index|device_count|seat_count)$/;

function convert(sql) {
  return sql
    // Timestamps keep ISO-8601 UTC text: identical comparison semantics in both
    // engines and no driver-level Date/timezone conversion in the hot path.
    .replace(/DEFAULT \(datetime\('now'\)\)/g, "DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS'))")
    // SQLite's INTEGER PRIMARY KEY AUTOINCREMENT → PostgreSQL identity column.
    // (Order matters: rewrite the column before stripping the keyword.)
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/INSERT OR IGNORE INTO/g, 'INSERT INTO __IGNORE__')
    // PRAGMAs are connection settings: SQLite sets them in the driver, and
    // PostgreSQL enforces FKs natively. Strip them from the DDL transcript.
    .replace(/^\s*PRAGMA[^;]*;\n?/gim, '')
    // `INSERT OR REPLACE` only appears in seeds (which are regenerated), never
    // in migrations; if one ever lands here, fail loudly instead of guessing.
    .replace(/\bINSERT OR REPLACE INTO\b/g, '/* REVIEW: INSERT OR REPLACE */ INSERT INTO');
}

/** Rewrite `col TYPE` declarations inside CREATE TABLE bodies. */
function convertColumnTypes(sql) {
  return sql.replace(
    /CREATE TABLE (?:IF NOT EXISTS )?([a-z_]+) \(([\s\S]*?)\n\);/g,
    (_full, table, body) => {
      const lines = body.split('\n').map((line) => {
        const m = /^(\s{2})([a-z_]+)(\s+)(TEXT|REAL|INTEGER|BLOB)(.*)$/.exec(line);
        if (!m) return line;
        const [, indent, col, gap, type, rest] = m;
        let pgType = type;
        // Boolean flags stay 0/1 (SMALLINT + CHECK) on *both* engines. Mapping
        // them to a native BOOLEAN would make the same application statement
        // bind integers to a boolean column, which PostgreSQL rejects — one
        // code path is worth more than a tidier type name. Documented in
        // db/postgres/README.md.
        if ((type === 'TEXT' || type === 'INTEGER') && BOOLEAN_COLUMNS.has(col)) pgType = 'SMALLINT';
        else if (type === 'REAL') pgType = 'DOUBLE PRECISION';
        else if (type === 'BLOB') pgType = 'BYTEA';
        else if (type === 'INTEGER' && INTEGER_HINTS.test(col)) pgType = 'INTEGER';
        // SQLite booleans are written as 0/1 by the app; normalise defaults.
        // `rest` may end with a trailing comma; keep it outside the CHECK so
        // the column list stays syntactically valid.
        const comma = rest.endsWith(',') ? ',' : '';
        const core = comma ? rest.slice(0, -1) : rest;
        const restOut = pgType === 'SMALLINT' && !/CHECK/i.test(core)
          ? `${core} CHECK (${col} IN (0,1))${comma}`
          : rest;
        // SQLite TEXT PKs holding slug ids stay as-is, but AUTOINCREMENT-style
        // surrogate keys become real uuids so concurrent inserts never collide.
        return `${indent}${col}${gap}${pgType}${restOut}`;
      });
      return `CREATE TABLE ${table} (${lines.join('\n')}\n);`;
    },
  );
}

/** `INSERT OR IGNORE` → `INSERT … ON CONFLICT DO NOTHING`, per statement. */
function addConflictClauses(sql) {
  return sql.replace(/INSERT INTO __IGNORE__ ([\s\S]*?);(\s*\n)/g, (_m, body, tail) => {
    return `INSERT INTO ${body} ON CONFLICT DO NOTHING;${tail}`;
  }).replace(/__IGNORE__/g, '');
}

function convertFile(file) {
  const src = fs.readFileSync(path.join(SRC, file), 'utf8');
  const header = `-- GENERATED from db/migrations/${file} — do not edit by hand.\n-- Regenerate with: node scripts/gen-pg-migrations.mjs\n\n`;
  return header + addConflictClauses(convertColumnTypes(convert(src)));
}

const files = fs.readdirSync(SRC).filter((f) => f.endsWith('.sql')).sort();
if (!files.length) {
  console.error('No migrations found.');
  process.exit(1);
}

const check = process.argv.includes('--check');
fs.mkdirSync(OUT, { recursive: true });

let stale = [];
for (const file of files) {
  const target = path.join(OUT, file);
  const next = convertFile(file);
  const prev = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (prev !== next) {
    stale.push(file);
    if (!check) fs.writeFileSync(target, next);
  }
}

// Remove PG migrations whose SQLite source disappeared (kept intentionally loud).
for (const existing of fs.readdirSync(OUT).filter((f) => f.endsWith('.sql'))) {
  if (!files.includes(existing)) {
    stale.push(`orphan:${existing}`);
    if (!check) fs.unlinkSync(path.join(OUT, existing));
  }
}

if (check) {
  if (stale.length) {
    console.error(`✗ PostgreSQL migrations are stale: ${stale.join(', ')}`);
    console.error('  Run: node scripts/gen-pg-migrations.mjs');
    process.exit(1);
  }
  console.log(`✓ PostgreSQL migrations in sync (${files.length} files)`);
} else {
  console.log(`✓ generated ${files.length} PostgreSQL migrations${stale.length ? ` (updated: ${stale.length})` : ''}`);
}
